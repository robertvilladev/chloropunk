def svg(rows):
    rows=[r for r in rows.strip('\n').split('\n')]
    w=16; h=16
    out=[]
    for y,r in enumerate(rows):
        assert len(r)<=16,(r,len(r))
        r=r.ljust(16,'.')
        x=0
        while x<16:
            ch=r[x]
            if ch=='.': x+=1; continue
            x2=x
            while x2<16 and r[x2]==ch: x2+=1
            out.append(f'<rect x="{x}" y="{y}" width="{x2-x}" height="1" fill="{P[ch]}"/>')
            x=x2
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16" shape-rendering="crispEdges">'+''.join(out)+'</svg>'
